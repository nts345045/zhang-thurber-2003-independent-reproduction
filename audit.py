#!/usr/bin/env python3
"""Maintain an explicit manuscript-panel audit without substituting field data."""
import csv
import json
from pathlib import Path

rows = []
generate = './build/dd generate configs/synthetic.cfg data/synthetic'
standard = './build/dd invert configs/synthetic.cfg data/synthetic standard'
dd = './build/dd invert configs/synthetic.cfg data/synthetic dd'

def add(panel, quantity, documentation, parameters, data, plot, status, limitation):
    rows.append(dict(panel=panel, quantity=quantity, documentation=documentation,
                     parameters=parameters, data_command=data, plot_command=plot,
                     status=status, limitation=limitation))

add('1', 'Horizontal true P-velocity slice', 'Synthetic Test, p.1877; caption 1',
    'Written sandwich profile, x=-35..35 km, y=-60..40 km; constant with depth',
    generate, 'python3 plot.py --figure 1', 'independently reproduced',
    'Physical velocity profile reconstructed from prose; plotting extent and depth chosen from model domain.')
add('2', 'Synthetic-test event/station geometry and inversion grid', 'Caption 2, p.1879',
    'Published 8x6x5 inversion grid; 120 independent sources and 32 independent stations, seed 2003',
    generate, 'python3 plot.py --figure 2', 'partially reproduced',
    'Grid recovered from caption. Original Loma Prieta coordinates are excluded and are not reconstructed from map pixels.')
for label, quantity, command in [('a', 'Standard tomographic P velocity', standard),
                                  ('b', 'DD tomographic P velocity', dd),
                                  ('c', 'True minus DD P velocity', dd),
                                  ('d', 'True minus standard P velocity', standard)]:
    add('3' + label, quantity + '; all generated depth slices', 'Synthetic Test pp.1877-1879; captions 3 pp.1880-1881',
        'Depths 0,3,7,11,16 km; grid from caption 2; noise 0.04 s and station bias +/-0.3 s; configs/synthetic.cfg',
        generate + ' && ' + command, 'python3 plot.py --figure 3' + label, 'partially reproduced',
        'Independent geometry, homogeneous initial velocity, and explicit replacements for unpublished numerical settings; numerical comparisons cannot isolate implementation from experiment differences.')
add('4', 'Hayward network, catalog seismicity, and inversion grid', 'Caption 4, p.1882',
    'Grid x=-35,-20,-10,-5,-4,-3,0,5,10,20,35; y=-30,-20,-10,0,10,20,30; z=0,4,8,12,20 km',
    'Unavailable: requires excluded observed coordinates', 'Unavailable: no source data', 'not reproduced',
    'Attempt: recovered written grid and required observation counts; no authorized coordinates for 1489 events or 52 stations. No invented field map is presented.')
for label, desc in [('a', 'NCSN catalog'), ('b', 'standard tomography'), ('c', 'DD location'), ('d', 'DD tomography')]:
    add('5' + label, 'Hayward event map: ' + desc, 'Event Locations pp.1881-1883; caption 5',
        '1489 earthquakes, 52 stations; 20257 absolute picks, 767127 catalog differences, 17955 precise differences',
        'Unavailable: requires excluded observations', 'Unavailable: no source data', 'not reproduced',
        'Attempt: traced input dependencies. Catalog picks, differential times and event identities cannot be inferred from written descriptions or regenerated by a physical forward model.')
for number, method in [(6, 'catalog'), (7, 'standard tomography'), (8, 'DD location'), (9, 'DD tomography')]:
    for label, projection in [('a', 'geographical map'), ('b', 'rotated Cartesian map'),
                              ('c', 'across-strike depth section AA-prime'), ('d', 'along-strike depth section BB-prime')]:
        add(str(number) + label, method + ': ' + projection, 'Event Locations pp.1882-1884; captions 6-9',
            'Center 37.72 N, 122.06 W; 35-degree anticlockwise rotation; map selection 37.83..37.91 N, -122.26..-122.18 E',
            'Unavailable: requires excluded event catalog and travel times', 'Unavailable: no source data', 'not reproduced',
            'Attempt: recovered projection convention and regional selection. Input event locations/identities and, for c/d, box membership are unavailable under the data restriction. No digitization used.')
for label, quantity in [('a', 'DD velocity'), ('b', 'standard velocity'), ('c', 'DD minus standard velocity')]:
    for y in [-30, -20, -10, 0, 10, 20, 30]:
        add('10{} (y={})'.format(label, y), 'Hayward across-strike ' + quantity,
            'Velocity Structure p.1884; caption 10 p.1887',
            'Published Hayward grid; smoothing weight 10; y={} km; hypocenters within 5 km'.format(y),
            'Unavailable: requires excluded Hayward observations', 'Unavailable: no field inversion output', 'not reproduced',
            'Attempt: recovered grid, smoothing choice and cross-section convention. The observational velocity contrast is an inversion result, not a forward-model input specified by prose.')
for label, quantity in [('a', 'resolution-matrix diagonal'), ('b', 'one-sigma velocity uncertainty')]:
    for y in [-30, -20, -10, 0, 10, 20, 30]:
        add('11{} (y={})'.format(label, y), 'Hayward ' + quantity,
            'Velocity Structure pp.1884,1886; caption 11 p.1888',
            'Absolute-data standard-tomography linearization at the DD velocity model; y={} km'.format(y),
            'Unavailable: requires excluded observation matrix and inferred field velocity', 'Unavailable: no field matrix', 'not reproduced',
            'Attempt: established dependency on the actual ray geometry, final field model, damping and data covariance. These cannot be replaced by an unrelated synthetic resolution matrix and called a reproduction.')

# Later authorization permits independently retrieved authoritative observations.
# Keep the baseline panel record, but do not repeat its superseded exclusion as
# the current reason no field result exists.
if Path('data/authoritative/hayward/pick_selection_manifest.json').exists():
    acquisition = json.loads(Path('data/authoritative/hayward/pick_selection_manifest.json').read_text())
    if acquisition['acquisition_complete']:
        for row in rows:
            if row['panel'] == '2':
                row['limitation'] = ('The saved baseline uses random geometry. A documented authoritative Loma Prieta subset is authorized; '
                                     'it has not yet replaced this experiment. No digitization used.')
            if int(row['panel'].split()[0].rstrip('abcd')) >= 4:
                row['data_command'] = ('Pending metadata clarification: python3 prepare_hayward.py; '
                                       './build/dd invert configs/hayward.cfg data/hayward MODE')
                row['plot_command'] = 'python3 plot_hayward.py (requires completed field outputs)'
                row['limitation'] = ('Authoritative subset acquired; calculation awaits clarification of missing NC.CMW1 epochs and borehole '
                                     'elevations at NC.CCH1/CGP1/CSU1. No corresponding result yet. The manuscript cohort and waveform differences remain unmatched.')
                if row['panel'].startswith('11'):
                    row['data_command'] += ('; ./build/dd linearize configs/hayward.cfg data/hayward dd; '
                                            'OPENBLAS_NUM_THREADS=1 python3 resolution_hayward.py')
                    row['limitation'] += (' The independent absolute-data resolution/noise algebra passes a small joint-matrix check; '
                                          'it has not been applied to a field model. Reported symmetric pick errors are interpreted as 1-sigma only as a declared assumption.')

Path('data').mkdir(exist_ok=True)
with open('data/panel_audit.csv', 'w', newline='') as f:
    writer = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator='\n')
    writer.writeheader()
    writer.writerows(rows)
Path('data/panel_audit.json').write_text(json.dumps(rows, indent=2) + '\n')
with open('FIGURE_AUDIT.md', 'w') as f:
    f.write('# Manuscript figure audit\n\n')
    f.write('Written-specification and input-availability audit. Numerical statuses must also be read with the run results in the report. Rows 10 and 11 enumerate each section separately. Figure 3 rows include all depth slices generated by the implementation.\n\n')
    for r in rows:
        f.write('## Panel ' + r['panel'] + '\n\n')
        for key, value in r.items():
            if key != 'panel':
                f.write('**{}:** {}\n\n'.format(key.replace('_', ' ').capitalize(), value))
    f.write('## Supplementary figures\n\nNo supplement is listed for this article on the original SSA issue contents or article abstract page. No supplementary figures were identified. Direct primary links and the check are recorded in reference/specification_notes.md.\n')
print('Wrote audit for {} panel/section entries.'.format(len(rows)))
